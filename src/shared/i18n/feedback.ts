export type FeedbackKey = keyof typeof feedbackMessages.ar;
export function feedbackText(key: FeedbackKey, locale: AppLocale = "ar"): string {
  return feedbackMessages[locale][key];
}
export function formatFeedback(key: FeedbackKey, values: { seconds?: number }, locale: AppLocale = "ar"): string {
  const message = feedbackText(key, locale);
  return values.seconds === undefined ? message : message.replace("{seconds}", String(values.seconds));
}
